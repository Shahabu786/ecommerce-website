package com.example.ecomm.dto;

public class AcInstallationDto {
    private String serviceName;
    private String fullName;
    private String email;
    private String phone;
    private String address;
    private String city;
    private String pincode;
    private String acBrand;
    private String acTon;
    private String date;
    private String timeSlot;
    private String notes;

    public AcInstallationDto() {}

    public String getServiceName() { return serviceName; }
    public void setServiceName(String serviceName) { this.serviceName = serviceName; }
    public String getFullName() { return fullName; }
    public void setFullName(String fullName) { this.fullName = fullName; }
    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }
    public String getPhone() { return phone; }
    public void setPhone(String phone) { this.phone = phone; }
    public String getAddress() { return address; }
    public void setAddress(String address) { this.address = address; }
    public String getCity() { return city; }
    public void setCity(String city) { this.city = city; }
    public String getPincode() { return pincode; }
    public void setPincode(String pincode) { this.pincode = pincode; }
    public String getAcBrand() { return acBrand; }
    public void setAcBrand(String acBrand) { this.acBrand = acBrand; }
    public String getAcTon() { return acTon; }
    public void setAcTon(String acTon) { this.acTon = acTon; }
    public String getDate() { return date; }
    public void setDate(String date) { this.date = date; }
    public String getTimeSlot() { return timeSlot; }
    public void setTimeSlot(String timeSlot) { this.timeSlot = timeSlot; }
    public String getNotes() { return notes; }
    public void setNotes(String notes) { this.notes = notes; }
}
